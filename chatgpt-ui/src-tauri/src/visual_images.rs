//! Read-only, task-scoped image delivery. No arbitrary file paths cross the IPC boundary.
use base64::{engine::general_purpose::STANDARD as BASE64, Engine as _};
use image::{ImageFormat, ImageReader, Limits};
use serde_json::Value;
use std::{fs::{self, File}, io::{Cursor, Read}, path::{Path, PathBuf}, sync::Mutex};

const MAX_FILE_BYTES: u64 = 25 * 1024 * 1024;
const MAX_MANIFEST_BYTES: u64 = 1024 * 1024;
const MAX_PIXELS: u64 = 16_000_000;
const MAX_DELIVERY_BYTES: usize = 6 * 1024 * 1024;
// Image decoding is serialized to bound peak native memory across visible cards.
static IMAGE_DECODE_LOCK: Mutex<()> = Mutex::new(());

fn valid_image_id(value: &str) -> bool {
    !value.is_empty() && value.len() <= 200
        && value.bytes().all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'-' | b'_'))
}

fn bounded_read(path: &Path, maximum: u64) -> Result<Vec<u8>, String> {
    let file = File::open(path).map_err(|error| format!("无法读取图片资料：{error}"))?;
    if file.metadata().map_err(|error| error.to_string())?.len() > maximum {
        return Err("图片或资料超过大小限制".into());
    }
    let mut bytes = Vec::new();
    file.take(maximum + 1).read_to_end(&mut bytes).map_err(|error| error.to_string())?;
    if bytes.len() as u64 > maximum { return Err("图片或资料超过大小限制".into()); }
    Ok(bytes)
}

fn owned_path(root: &Path, candidate: &Path) -> Result<PathBuf, String> {
    let root = root.canonicalize().map_err(|_| "当前任务没有图片资料".to_string())?;
    let path = candidate.canonicalize().map_err(|_| "图片已移动或不存在".to_string())?;
    if !path.starts_with(&root) || !path.is_file() { return Err("图片不属于当前任务".into()); }
    Ok(path)
}

fn resolve_image(data_dir: &Path, task_id: &str, image_id: &str, source: &str) -> Result<PathBuf, String> {
    if !super::valid_task_id(task_id) || !valid_image_id(image_id) { return Err("图片任务或标识无效".into()); }
    match source {
        "visual" => {
            let root = data_dir.join("visual").join(task_id);
            let manifest = owned_path(&root, &root.join("manifest.json"))?;
            let value: Value = serde_json::from_slice(&bounded_read(&manifest, MAX_MANIFEST_BYTES)?)
                .map_err(|_| "视觉资料清单格式无效".to_string())?;
            if value.get("lease_id").and_then(Value::as_str) != Some(task_id) { return Err("视觉清单任务不匹配".into()); }
            let state = value.get("visual_mode").ok_or("视觉清单缺少状态")?;
            for key in ["references", "observations"] {
                if let Some(records) = state.get(key).and_then(Value::as_array) {
                    for record in records.iter().take(128) {
                        if record.get("id").and_then(Value::as_str) != Some(image_id) { continue; }
                        if record.get("kind").and_then(Value::as_str) == Some("text") { return Err("该参考资料是文本，不是图片".into()); }
                        let path = record.get("path").and_then(Value::as_str).ok_or("视觉图片缺少路径")?;
                        if key == "references" {
                            let media_references = data_dir.join("references").join(task_id);
                            let legacy_references = root.join("references");
                            if let Ok(owned) = owned_path(&media_references, Path::new(path)) { return Ok(owned); }
                            return owned_path(&legacy_references, Path::new(path));
                        }
                        return owned_path(&root.join("observations"), Path::new(path));
                    }
                }
            }
            Err("没有找到当前任务的这张视觉图片".into())
        }
        "user" => {
            // Attachment filenames are generated by persist_attachments, never user-controlled IDs.
            // This remains readable after inbox compaction and after the lease completes.
            if !image_id.starts_with("att-") { return Err("用户附件标识无效".into()); }
            let root = data_dir.join("attachments").join(task_id);
            let prefix = format!("{image_id}__");
            let mut matches = fs::read_dir(&root).map_err(|_| "当前任务没有用户图片附件".to_string())?
                .filter_map(Result::ok)
                .map(|entry| entry.path())
                .filter(|path| path.file_name().and_then(|name| name.to_str()).is_some_and(|name| name.starts_with(&prefix)));
            let first = matches.next().ok_or("用户图片附件不存在")?;
            if matches.next().is_some() { return Err("用户图片附件标识有歧义".into()); }
            owned_path(&root, &first)
        }
        _ => Err("图片来源仅支持 user / visual".into()),
    }
}

fn delivery_data_uri(bytes: Vec<u8>, thumbnail: bool) -> Result<String, String> {
    let _guard = IMAGE_DECODE_LOCK.lock().map_err(|_| "图片解码器不可用".to_string())?;
    let reader = ImageReader::new(Cursor::new(&bytes)).with_guessed_format().map_err(|error| error.to_string())?;
    let format = reader.format().ok_or("文件不是受支持的位图")?;
    if !matches!(format, ImageFormat::Png | ImageFormat::Jpeg | ImageFormat::WebP | ImageFormat::Gif | ImageFormat::Bmp) {
        return Err("仅支持 PNG/JPEG/WebP/GIF/BMP 位图，不加载 SVG 或可执行内容".into());
    }
    let (width, height) = reader.into_dimensions().map_err(|error| format!("图片尺寸无效：{error}"))?;
    if width == 0 || height == 0 || u64::from(width) * u64::from(height) > MAX_PIXELS {
        return Err("图片尺寸超过 1600 万像素限制".into());
    }
    let mut limits = Limits::default();
    limits.max_image_width = Some(16384);
    limits.max_image_height = Some(16384);
    limits.max_alloc = Some(128 * 1024 * 1024);
    let mut reader = ImageReader::with_format(Cursor::new(&bytes), format);
    reader.limits(limits);
    let image = reader.decode().map_err(|error| format!("图片无法解码：{error}"))?;
    let image = if thumbnail { image.thumbnail(288, 180) } else { image.thumbnail(1600, 1600) };
    let mut output = Cursor::new(Vec::new());
    image.write_to(&mut output, ImageFormat::Png).map_err(|error| error.to_string())?;
    let mut mime = "image/png";
    if output.get_ref().len() > MAX_DELIVERY_BYTES {
        output = Cursor::new(Vec::new());
        image.to_rgb8().write_to(&mut output, ImageFormat::Jpeg).map_err(|error| error.to_string())?;
        mime = "image/jpeg";
    }
    if output.get_ref().len() > MAX_DELIVERY_BYTES { return Err("图片预览仍超过输出大小限制".into()); }
    Ok(format!("data:{mime};base64,{}", BASE64.encode(output.into_inner())))
}

pub fn image_data_uri(data_dir: &Path, task_id: &str, image_id: &str, source: &str, thumbnail: bool) -> Result<String, String> {
    let path = resolve_image(data_dir, task_id, image_id, source)?;
    delivery_data_uri(bounded_read(&path, MAX_FILE_BYTES)?, thumbnail)
}

#[cfg(test)]
mod tests {
    use super::*;
    fn root(name: &str) -> PathBuf {
        let path = std::env::temp_dir().join(format!("qh-visual-image-{name}-{}-{}", std::process::id(), super::super::unix_millis()));
        fs::create_dir_all(&path).unwrap();
        path
    }
    const TASK: &str = "11111111111111111111111111111111";
    fn png(path: &Path) { image::RgbImage::new(32, 16).save_with_format(path, ImageFormat::Png).unwrap(); }
    fn manifest(root: &Path, path: &Path) {
        let dir = root.join("visual").join(TASK);
        fs::create_dir_all(&dir).unwrap();
        fs::write(dir.join("manifest.json"), serde_json::json!({"lease_id":TASK,
            "visual_mode":{"references":[{"id":"ref-test", "kind":"image", "path":path}],"observations":[]}}).to_string()).unwrap();
    }
    #[test]
    fn visual_image_requires_owned_manifest_and_path() {
        let root = root("owned");
        let dir = root.join("references").join(TASK);
        fs::create_dir_all(&dir).unwrap();
        let path = dir.join("ref-test.png"); png(&path); manifest(&root, &path);
        assert!(image_data_uri(&root,TASK,"ref-test","visual",true).unwrap().starts_with("data:image/png;base64,"));
        assert!(image_data_uri(&root,TASK,"ref-missing","visual",false).is_err());
        assert!(image_data_uri(&root,"../outside","ref-test","visual",false).is_err());
        let _ = fs::remove_dir_all(root);
    }
    #[test]
    fn tampered_manifest_cannot_escape_owned_references() {
        let root = root("escape");
        let outside = root.join("outside.png"); png(&outside);
        fs::create_dir_all(root.join("visual").join(TASK).join("references")).unwrap();
        manifest(&root,&outside);
        assert!(image_data_uri(&root,TASK,"ref-test","visual",false).is_err());
        let _ = fs::remove_dir_all(root);
    }
    #[test]
    fn user_attachments_are_image_decoded_not_mime_trusted() {
        let root = root("user");
        let dir = root.join("attachments").join(TASK); fs::create_dir_all(&dir).unwrap();
        let path = dir.join("att-test__actually-text.png"); fs::write(&path,b"<svg onload='alert(1)'></svg>").unwrap();
        assert!(image_data_uri(&root,TASK,"att-test","user",false).is_err());
        png(&path);
        assert!(image_data_uri(&root,TASK,"att-test","user",false).is_ok());
        assert!(image_data_uri(&root,TASK,"../att-test","user",false).is_err());
        let _ = fs::remove_dir_all(root);
    }
}
